create table if not exists public.players (
  id bigint generated by default as identity primary key,
  name varchar(20) not null,
  name_key varchar(20) not null unique,
  elo integer not null default 1200 check (elo between 100 and 4000),
  password_hash text,
  password_salt text,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

-- Pour les projets déjà créés avec v51/v52 :
alter table public.players
  add column if not exists password_hash text;

alter table public.players
  add column if not exists password_salt text;

create unique index if not exists players_name_key_unique
  on public.players (name_key);

create index if not exists players_elo_ranking_idx
  on public.players (elo desc, updated_at asc);

create table if not exists public.sessions (
  id bigint generated by default as identity primary key,
  player_id bigint not null references public.players(id) on delete cascade,
  token_hash text not null unique,
  expires_at timestamptz not null,
  created_at timestamptz not null default now()
);

create index if not exists sessions_token_hash_idx
  on public.sessions (token_hash);

create index if not exists sessions_player_idx
  on public.sessions (player_id);

alter table public.players enable row level security;
alter table public.sessions enable row level security;

-- Le navigateur n'accède jamais directement à ces tables.
-- Seules les Netlify Functions utilisent la Secret key / service_role.
grant usage on schema public to service_role;

grant select, insert, update, delete
  on table public.players
  to service_role;

grant select, insert, update, delete
  on table public.sessions
  to service_role;

grant usage, select
  on sequence public.players_id_seq
  to service_role;

grant usage, select
  on sequence public.sessions_id_seq
  to service_role;

-- ==========================================================
-- V69 : historique des parties / statistiques de profil
-- ==========================================================
create table if not exists public.games (
  id bigint generated by default as identity primary key,
  player_id bigint not null references public.players(id) on delete cascade,
  mode varchar(16) not null check (mode in ('local','ai','remote')),
  opponent_name varchar(40) not null default 'Adversaire',
  opponent_elo integer,
  player_color char(1) not null check (player_color in ('w','b')),
  result varchar(8) not null check (result in ('win','loss','draw')),
  reason varchar(20),
  time_control varchar(20) not null default '10 min',
  rated boolean not null default false,
  elo_before integer,
  elo_after integer,
  elo_delta integer not null default 0,
  created_at timestamptz not null default now()
);

create index if not exists games_player_created_idx
  on public.games (player_id, created_at desc);

alter table public.games enable row level security;

grant select, insert, update, delete
  on table public.games
  to service_role;

grant usage, select
  on sequence public.games_id_seq
  to service_role;

-- ==========================================================
-- V70 : parties différées 3 jours par coup
-- ==========================================================
create table if not exists public.correspondence_games (
  id bigint generated by default as identity primary key,
  room_code varchar(6) not null unique,
  white_player_id bigint not null references public.players(id) on delete cascade,
  black_player_id bigint references public.players(id) on delete cascade,
  fen text not null default 'rnbqkbnr/pppppppp/8/8/8/8/PPPPPPPP/RNBQKBNR w KQkq - 0 1',
  moves jsonb not null default '[]'::jsonb,
  turn char(1) not null default 'w' check (turn in ('w','b')),
  status varchar(12) not null default 'waiting' check (status in ('waiting','active','completed')),
  result varchar(8) check (result in ('white','black','draw')),
  reason varchar(20),
  deadline_at timestamptz,
  version integer not null default 0,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  finished_at timestamptz
);

create index if not exists correspondence_white_idx on public.correspondence_games (white_player_id, updated_at desc);
create index if not exists correspondence_black_idx on public.correspondence_games (black_player_id, updated_at desc);
create index if not exists correspondence_status_deadline_idx on public.correspondence_games (status, deadline_at);

alter table public.correspondence_games enable row level security;
grant select, insert, update, delete on table public.correspondence_games to service_role;
grant usage, select on sequence public.correspondence_games_id_seq to service_role;

alter table public.games drop constraint if exists games_mode_check;
alter table public.games add constraint games_mode_check check (mode in ('local','ai','remote','correspondence'));
alter table public.games add column if not exists correspondence_game_id bigint references public.correspondence_games(id) on delete set null;
create unique index if not exists games_player_correspondence_unique
  on public.games (player_id, correspondence_game_id)
  where correspondence_game_id is not null;

